const OSRM = 'https://router.project-osrm.org/route/v1/driving'
/** About 20 m: simpler lines, still on the road at street zoom */
const SIMPLIFY_TOLERANCE_DEG = 0.0002
/** OSRM's demo server asks for at most one request a second */
const REQUEST_GAP_MS = 1100

const round = (value: number) => Math.round(value * 1e5) / 1e5
const slug = (text: string) =>
  text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')

async function roadBetween(from: { lng: number; lat: number }, to: { lng: number; lat: number }) {
  const url = `${OSRM}/${from.lng},${from.lat};${to.lng},${to.lat}?overview=full&geometries=geojson`
  const response = await fetch(url, { headers: { 'user-agent': 'fleetops-demo-routes' } })
  if (!response.ok) throw new Error(`${url} answered ${response.status}`)

  const body = (await response.json()) as {
    routes?: { geometry: { coordinates: [number, number][] } }[]
  }
  const coordinates = body.routes?.[0]?.geometry.coordinates
  if (!coordinates) throw new Error(`No route from ${url}`)
  // Full geometry has a point every few metres; keep only the ones that change the shape
  const { geometry } = simplify(lineString(coordinates), { tolerance: SIMPLIFY_TOLERANCE_DEG })
  return geometry.coordinates.map(([lng = 0, lat = 0]): [number, number] => [
    round(lng),
    round(lat),
  ])
}

const routes: DemoRoute[] = []
for (const depot of DEMO_DEPOTS) {
  for (const destination of DESTINATIONS[depot.name] ?? []) {
    routes.push({
      id: slug(`${depot.name} ${destination.name}`),
      name: `${depot.name} → ${destination.name}`,
      kind: destination.kind,
      path: await roadBetween(depot.location, destination),
    })
    console.log(`${routes.at(-1)?.name}: ${routes.at(-1)?.path.length} points`)
    await new Promise((resolve) => setTimeout(resolve, REQUEST_GAP_MS))
  }
}

const source = [
  '// Generated by scripts/fetch-demo-routes.ts from OSRM driving routes over OpenStreetMap data',
  '// (© OpenStreetMap contributors, ODbL). Do not edit by hand.',
  "import type { DemoRoute } from './simulation.ts'",
  '',
  'export const DEMO_ROUTES: DemoRoute[] = [',
  ...routes.map((route) => `  ${JSON.stringify(route)},`),
  ']',
  '',
].join('\n')

await writeFile(
  new URL('../src/modules/tracking/domain/demo-routes.gen.ts', import.meta.url),
  source,
)
console.log(`${routes.length} routes written`)
