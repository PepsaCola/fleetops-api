// Fetches road geometry for the demo routes from OSRM's public server (OpenStreetMap data) and
// writes it next to the simulation. Run it only when the routes below change:
//   npx tsx scripts/fetch-demo-routes.ts

type Destination = { name: string; kind: RouteKind; lng: number; lat: number }

